#!/usr/bin/env python3
"""
Generate pre-tokenized 2-hop reasoning dataset for fine-tuning.

Uses problem data from scripts/multihop/ (adapted from Ryan Greenblatt's multi_hop repo).
Splits problems into strictly isolated fewshot/train/val/val_eval/test pools
(no problem appears in more than one pool).

Prompt structure (same as generate_2hop_dataset.py):
    system:    instruction + 5 few-shot Q/A examples
    user:      Question: <question>
    assistant: [Filler: 1 2 3 ... N\n]Answer: <answer>   ← generated by model

CoT assistant turn:
    <chain[0]['fact']>: <chain[0]['value']>
    <chain[1]['fact']>: <chain[1]['value']>
    Answer: <answer>

Loss is computed only on answer tokens for filler/baseline; on all assistant
tokens for CoT (same convention as generate_2hop_dataset.py).

Usage:
    python scripts/generate_multihop_dataset.py \\
        --tokenizer Qwen/Qwen2.5-7B-Instruct \\
        --outdir data/datasets/multihop_2hop \\
        --n-val 200 --n-val-eval 200 --n-test 200 \\
        --eval-filler-lengths 0,64,128,256 \\
        --cot-mixture \\
        --known-problems data/known_facts/multihop/known_problems.json
"""
import argparse
import json
import pathlib
import random
import sys
from typing import Any, Dict, List, Optional

from transformers import AutoTokenizer

# ── Import from local multihop/ subdirectory ──────────────────────────────────
MULTIHOP_DIR = pathlib.Path(__file__).resolve().parent / "multihop"
sys.path.insert(0, str(MULTIHOP_DIR))

from generate_dataset import generate_all_problems  # type: ignore  # noqa: E402


# ── Prompt construction ────────────────────────────────────────────────────────

INSTRUCTION = (
    "You will be given a question. Answer immediately using the format "
    "'Answer: [ANSWER]' where [ANSWER] is just the answer, nothing else. "
    "No explanation, no words, no reasoning, just the answer."
)


def build_system_prompt(fewshot_problems: List[Dict]) -> str:
    """System prompt: instruction + few-shot Q/A pairs."""
    lines = [INSTRUCTION, "", "Examples:", ""]
    for p in fewshot_problems:
        lines.append(f"Question: {p['question']}")
        lines.append(f"Answer: {p['answer']}")
        lines.append("")
    return "\n".join(lines).strip()


def build_cot_response(problem: Dict) -> str:
    """Build CoT text from chain steps + answer, e.g.:
        Atomic number of Zinc: 30
        State that joined the union 30th: Wisconsin
        Answer: Wisconsin
    """
    parts = []
    for step in problem.get("chain", []):
        parts.append(f"{step['fact']}: {step['value']}")
    parts.append(f"Answer: {problem['answer']}")
    return "\n".join(parts)


def build_filler_prefill(n: int, filler_type: str = "counting") -> str:
    """Build assistant prefill up to and including 'Answer:' (no trailing space)."""
    if n == 0:
        return "Answer:"
    if filler_type == "counting":
        filler = " ".join(str(i) for i in range(1, n + 1))
    else:  # dots
        filler = "." * n
    return f"Filler: {filler}\nAnswer:"


# ── Tokenization ───────────────────────────────────────────────────────────────

def _encode_prompt(
    problem: Dict,
    tok: Any,
    fewshot_problems: List[Dict],
    filler_len: int,
    filler_type: str,
) -> List[int]:
    """Encode everything up to and including 'Answer:' (the prompt the model sees)."""
    messages = [
        {"role": "system", "content": build_system_prompt(fewshot_problems)},
        {"role": "user", "content": f"Question: {problem['question']}"},
    ]
    prompt_text = tok.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    prompt_text += build_filler_prefill(filler_len, filler_type)
    return tok.encode(prompt_text, add_special_tokens=False)


def tokenize_filler_example(
    problem: Dict,
    filler_len: int,
    tok: Any,
    fewshot_problems: List[Dict],
    filler_type: str = "counting",
) -> Dict:
    """Pre-tokenize a filler/baseline example.
    Labels: -100 for prompt+prefill, real labels only for answer tokens.
    """
    prompt_ids = _encode_prompt(problem, tok, fewshot_problems, filler_len, filler_type)

    # Space before answer prevents the answer token from merging with 'Answer:'
    answer_ids = tok.encode(" " + str(problem["answer"]), add_special_tokens=False)
    if tok.eos_token_id is not None:
        answer_ids = answer_ids + [tok.eos_token_id]

    input_ids = prompt_ids + answer_ids
    labels = [-100] * len(prompt_ids) + answer_ids
    attention_mask = [1] * len(input_ids)

    return {
        "prompt_ids": prompt_ids,
        "answer_ids": answer_ids,
        "input_ids": input_ids,
        "labels": labels,
        "attention_mask": attention_mask,
    }


def tokenize_cot_example(
    problem: Dict,
    tok: Any,
    fewshot_problems: List[Dict],
) -> Dict:
    """Pre-tokenize a CoT example.
    Labels: -100 for prompt; all CoT+answer tokens get real labels.
    """
    messages = [
        {"role": "system", "content": build_system_prompt(fewshot_problems)},
        {"role": "user", "content": f"Question: {problem['question']}"},
    ]
    prompt_text = tok.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    prompt_ids = tok.encode(prompt_text, add_special_tokens=False)

    cot_ids = tok.encode(build_cot_response(problem), add_special_tokens=False)
    if tok.eos_token_id is not None:
        cot_ids = cot_ids + [tok.eos_token_id]

    input_ids = prompt_ids + cot_ids
    labels = [-100] * len(prompt_ids) + cot_ids
    attention_mask = [1] * len(input_ids)

    # answer_ids stored for eval reference (not used in loss)
    answer_ids = tok.encode(" " + str(problem["answer"]), add_special_tokens=False)

    return {
        "prompt_ids": prompt_ids,
        "answer_ids": answer_ids,
        "input_ids": input_ids,
        "labels": labels,
        "attention_mask": attention_mask,
    }


# ── Row helpers ────────────────────────────────────────────────────────────────

def _base_row(
    problem: Dict,
    row_id: str,
    split: str,
    filler_len: int,
    filler_type: str,
    sequence_type: str = "filler",
) -> Dict:
    return {
        "id": row_id,
        "split": split,
        "sequence_type": sequence_type,
        "question": problem["question"],
        "answer": str(problem["answer"]),
        "hops": problem["hops"],
        "problem_type": problem["type"],
        "chain": [{"fact": s["fact"], "value": str(s["value"])} for s in problem["chain"]],
        "filler_len": filler_len,
        "filler_type": filler_type,
    }


# ── Split builders ─────────────────────────────────────────────────────────────

def build_train_split(
    problems: List[Dict],
    n_train: int,
    filler_lens: List[int],
    tok: Any,
    fewshot_problems: List[Dict],
    filler_type: str = "counting",
    cot_mixture: bool = False,
    rng: Optional[random.Random] = None,
) -> List[Dict]:
    """Generate training examples.

    Each of the n_train steps picks a random problem and a random filler length.
    With cot_mixture, each filler example is paired with a CoT example for the
    same problem (50/50 mix, following Pfau et al. 2024).
    If n_train > len(problems), problems are reused with different N values.
    """
    if rng is None:
        rng = random.Random(42)

    rows: List[Dict] = []
    for _ in range(n_train):
        problem = rng.choice(problems)
        filler_len = rng.choice(filler_lens)

        row_id = f"train-{len(rows):05d}"
        base = _base_row(problem, row_id, "train", filler_len, filler_type, "filler")
        tok_fields = tokenize_filler_example(problem, filler_len, tok, fewshot_problems, filler_type)
        rows.append({**base, **tok_fields})

        if cot_mixture:
            cot_id = f"train-{len(rows):05d}"
            cot_base = _base_row(problem, cot_id, "train", 0, filler_type, "cot")
            cot_tok = tokenize_cot_example(problem, tok, fewshot_problems)
            rows.append({**cot_base, **cot_tok})

    return rows


def build_val_split(
    problems: List[Dict],
    filler_lens: List[int],
    tok: Any,
    fewshot_problems: List[Dict],
    filler_type: str = "counting",
    cot_mixture: bool = False,
    rng: Optional[random.Random] = None,
) -> List[Dict]:
    """Validation split for loss tracking (one filler example per problem,
    plus CoT example if cot_mixture). Mirrors train distribution."""
    if rng is None:
        rng = random.Random(42)

    rows: List[Dict] = []
    for i, problem in enumerate(problems):
        filler_len = rng.choice(filler_lens)

        row_id = f"val-{len(rows):05d}"
        base = _base_row(problem, row_id, "val", filler_len, filler_type, "filler")
        tok_fields = tokenize_filler_example(problem, filler_len, tok, fewshot_problems, filler_type)
        rows.append({**base, **tok_fields})

        if cot_mixture:
            cot_id = f"val-{len(rows):05d}"
            cot_base = _base_row(problem, cot_id, "val", 0, filler_type, "cot")
            cot_tok = tokenize_cot_example(problem, tok, fewshot_problems)
            rows.append({**cot_base, **cot_tok})

    return rows


def build_eval_split(
    problems: List[Dict],
    split: str,
    filler_lens: List[int],
    tok: Any,
    fewshot_problems: List[Dict],
    filler_type: str = "counting",
) -> List[Dict]:
    """Eval split: every problem × every filler length = one row each.
    Enables paired comparison across N values."""
    rows: List[Dict] = []
    for problem in problems:
        for filler_len in filler_lens:
            row_id = f"{split}-{len(rows):05d}"
            base = _base_row(problem, row_id, split, filler_len, filler_type, "filler")
            tok_fields = tokenize_filler_example(problem, filler_len, tok, fewshot_problems, filler_type)
            rows.append({**base, **tok_fields})
    return rows


# ── I/O ────────────────────────────────────────────────────────────────────────

def write_jsonl(rows: List[Dict], path: pathlib.Path) -> None:
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"  Wrote {len(rows):,} examples → {path}")


# ── Main ───────────────────────────────────────────────────────────────────────

def main() -> None:
    ap = argparse.ArgumentParser(
        description="Generate pre-tokenized 2-hop dataset from multi_hop problems."
    )
    ap.add_argument("--tokenizer", required=True,
                    help="HuggingFace tokenizer name or path")
    ap.add_argument("--outdir", required=True,
                    help="Output directory")
    ap.add_argument("--n-fewshot", type=int, default=5,
                    help="Few-shot examples reserved for system prompt (default: 5)")
    ap.add_argument("--n-train", type=int, default=None,
                    help="Training examples to generate (default: 1x all remaining problems). "
                         "If larger than the pool, problems are reused with different N values.")
    ap.add_argument("--n-val", type=int, default=200,
                    help="Problems for val.jsonl and val_eval.jsonl (same pool, default: 200)")
    ap.add_argument("--n-test", type=int, default=200,
                    help="Problems for test.jsonl (default: 200)")
    ap.add_argument("--eval-filler-lengths", type=str, default="0,64,128,256",
                    help="Comma-separated filler lengths for eval/test splits (default: 0,64,128,256)")
    ap.add_argument("--filler-type", choices=["counting", "dots"], default="counting",
                    help="Filler token style (default: counting)")
    ap.add_argument("--cot-mixture", action="store_true",
                    help="Add a CoT example alongside every filler training example (50/50)")
    ap.add_argument("--only-salient-facts", action="store_true",
                    help="Use only salient-facts subset (fewer but more prominent problems)")
    ap.add_argument("--known-problems", type=str, default=None,
                    help="Path to known_problems.json from knowledge_check.py. "
                         "If given, only problems whose questions appear in this file are used.")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--cache-dir", default=None,
                    help="HuggingFace cache directory")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    outdir = pathlib.Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    eval_filler_lengths = [int(x.strip()) for x in args.eval_filler_lengths.split(",")]

    # ── Tokenizer ─────────────────────────────────────────────────────────────
    print(f"Loading tokenizer: {args.tokenizer}")
    tok = AutoTokenizer.from_pretrained(
        args.tokenizer, use_fast=True, cache_dir=args.cache_dir
    )
    if tok.pad_token_id is None:
        tok.pad_token = tok.eos_token

    # ── Generate problems ──────────────────────────────────────────────────────
    print("Generating 2-hop problems from multi_hop dataset...")
    _, all_2hop, _, _ = generate_all_problems(
        only_salient_facts=args.only_salient_facts
    )
    print(f"  Total 2-hop problems available: {len(all_2hop)}")

    if args.known_problems:
        known_path = pathlib.Path(args.known_problems)
        known_questions = {p["question"] for p in json.loads(known_path.read_text())}
        before = len(all_2hop)
        all_2hop = [p for p in all_2hop if p["question"] in known_questions]
        print(f"  After filtering to known problems: {len(all_2hop)} ({before - len(all_2hop)} removed)")

    rng.shuffle(all_2hop)

    # ── Validate split sizes ───────────────────────────────────────────────────
    # val and val_eval share the same problem pool (different file formats only)
    n_reserved = args.n_fewshot + args.n_val + args.n_test
    if n_reserved > len(all_2hop):
        raise SystemExit(
            f"Need {n_reserved} problems for fewshot+val+test "
            f"but only {len(all_2hop)} available. Reduce split sizes."
        )

    # ── Carve out strictly isolated pools ─────────────────────────────────────
    cursor = 0
    fewshot_pool = all_2hop[cursor:cursor + args.n_fewshot]; cursor += args.n_fewshot
    val_pool     = all_2hop[cursor:cursor + args.n_val];     cursor += args.n_val
    test_pool    = all_2hop[cursor:cursor + args.n_test];    cursor += args.n_test
    train_pool   = all_2hop[cursor:]  # all remaining problems
    # val_eval reuses the same problems as val (different format: all N values)
    val_eval_pool = val_pool

    n_train = args.n_train if args.n_train is not None else len(train_pool)

    print(f"\nProblem pools:")
    print(f"  fewshot:              {len(fewshot_pool)}")
    print(f"  val / val_eval:       {len(val_pool)}  (shared)")
    print(f"  test:                 {len(test_pool)}")
    print(f"  train (pool):         {len(train_pool)} unique → {n_train} training examples")
    if args.cot_mixture:
        print(f"  (cot_mixture: each filler example paired with a CoT example)")

    if len(train_pool) == 0:
        raise SystemExit(
            "No problems left for training after reserving fewshot/val/val_eval/test. "
            "Reduce split sizes."
        )

    # ── Tokenize ───────────────────────────────────────────────────────────────
    print(f"\nTokenizing...")

    print("  train...")
    train_rows = build_train_split(
        train_pool, n_train, eval_filler_lengths, tok, fewshot_pool,
        args.filler_type, args.cot_mixture, rng,
    )

    print("  val (loss tracking)...")
    val_rows = build_val_split(
        val_pool, eval_filler_lengths, tok, fewshot_pool,
        args.filler_type, args.cot_mixture, rng,
    )

    print("  val_eval (accuracy)...")
    val_eval_rows = build_eval_split(
        val_eval_pool, "val_eval", eval_filler_lengths, tok, fewshot_pool, args.filler_type,
    )

    print("  test...")
    test_rows = build_eval_split(
        test_pool, "test", eval_filler_lengths, tok, fewshot_pool, args.filler_type,
    )

    # ── Write JSONL ────────────────────────────────────────────────────────────
    print("\nWriting JSONL files...")
    write_jsonl(train_rows,    outdir / "train.jsonl")
    write_jsonl(val_rows,      outdir / "val.jsonl")
    write_jsonl(val_eval_rows, outdir / "val_eval.jsonl")
    write_jsonl(test_rows,     outdir / "test.jsonl")

    # ── Manifest ───────────────────────────────────────────────────────────────
    fewshot_raw = [
        {
            "question": p["question"],
            "answer":   str(p["answer"]),
            "chain":    p["chain"],
            "type":     p["type"],
        }
        for p in fewshot_pool
    ]

    manifest = {
        "tokenizer":           args.tokenizer,
        "filler_type":         args.filler_type,
        "eval_filler_lengths": eval_filler_lengths,
        "n_fewshot":           args.n_fewshot,
        "cot_mixture":         args.cot_mixture,
        "only_salient_facts":  args.only_salient_facts,
        "known_problems_filter": args.known_problems,
        "seed":                args.seed,
        "fewshot_examples":    fewshot_raw,
        "example_counts": {
            "train":    len(train_rows),
            "val":      len(val_rows),
            "val_eval": len(val_eval_rows),
            "test":     len(test_rows),
        },
        "unique_problems": {
            "total_2hop":        len(all_2hop),
            "fewshot":           len(fewshot_pool),
            "train":             len(train_pool),
            "val_and_val_eval":  len(val_pool),  # shared pool
            "test":              len(test_pool),
        },
    }
    (outdir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"  Wrote manifest → {outdir / 'manifest.json'}")

    # ── Problem pools (for reference / extra test generation) ─────────────────
    problem_pools = {
        split: [{"question": p["question"], "answer": str(p["answer"]), "type": p["type"]}
                for p in pool]
        for split, pool in [
            ("fewshot", fewshot_pool),
            ("train",   train_pool),
            ("val",     val_pool),   # val_eval uses the same pool
            ("test",    test_pool),
        ]
    }
    (outdir / "problem_pools.json").write_text(
        json.dumps(problem_pools, indent=2), encoding="utf-8"
    )
    print(f"  Wrote problem pools → {outdir / 'problem_pools.json'}")

    # ── Summary ────────────────────────────────────────────────────────────────
    print(f"\n{'='*60}")
    print(f"Dataset: {outdir}")
    print(f"  train.jsonl:    {len(train_rows):,}  ({len(train_pool)} unique problems × ~{n_train//len(train_pool):.0f}x)")
    print(f"  val.jsonl:      {len(val_rows):,}  ({len(val_pool)} problems, loss tracking)")
    print(f"  val_eval.jsonl: {len(val_eval_rows):,}  ({len(val_eval_pool)} problems × {len(eval_filler_lengths)} N values, shared pool with val)")
    print(f"  test.jsonl:     {len(test_rows):,}  ({len(test_pool)} problems × {len(eval_filler_lengths)} N values)")
    print(f"  Filler lengths: {eval_filler_lengths}")
    print(f"  Filler type:    {args.filler_type}")
    print(f"  CoT mixture:    {args.cot_mixture}")
    print(f"{'='*60}")

    # Show a couple of decoded examples
    print("\nDecoded example (filler, N=0):")
    n0_rows = [r for r in test_rows if r["filler_len"] == 0]
    if n0_rows:
        ex = n0_rows[0]
        prompt_tail = tok.decode(ex["prompt_ids"])[-300:]
        answer_text = tok.decode(ex["answer_ids"])
        print(f"  Q: {ex['question']}")
        print(f"  Expected answer: {ex['answer']}")
        print(f"  Prompt tail: ...{prompt_tail}")
        print(f"  Answer tokens: {answer_text!r}")

    if args.cot_mixture:
        print("\nDecoded CoT example:")
        cot_rows = [r for r in train_rows if r["sequence_type"] == "cot"]
        if cot_rows:
            ex = cot_rows[0]
            cot_text = tok.decode([t for t in ex["labels"] if t != -100])
            print(f"  Q: {ex['question']}")
            print(f"  CoT response: {cot_text!r}")


if __name__ == "__main__":
    main()
